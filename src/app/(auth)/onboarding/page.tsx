import type { Metadata } from "next";
import { Suspense } from "react";
import { cookies } from "next/headers";
import { REFERRAL_COOKIE } from "@utils/referrals";
import { requireAuth } from "@/app/_lib/auth";
import { db, members } from "@core/database";
import { eq } from "drizzle-orm";
import { isAutoGeneratedUsername } from "@utils/onboarding";
import { OnboardingForm } from "./_components/onboarding-form";

export const metadata: Metadata = {
  title: "Join Fort Worth DAO",
};

export default async function OnboardingPage() {
  const referralCode = (await cookies()).get(REFERRAL_COOKIE)?.value ?? "";
  const auth = await requireAuth();
  const [member] = await db
    .select()
    .from(members)
    .where(eq(members.userId, auth.user.id));
  const text = (value: unknown) =>
    typeof value === "string"
      ? value
      : Array.isArray(value)
        ? value.join(", ")
        : "";
  const initialProfile = member
    ? {
        username: isAutoGeneratedUsername(auth.user.username)
          ? ""
          : (auth.user.username ?? ""),
        firstName: member.firstName ?? "",
        lastName: member.lastName ?? "",
        email: auth.verifiedEmail ?? "",
        termsAccepted: !!member.termsAcceptedAt,
        phone: member.phone ?? "",
        employer: member.employer ?? "",
        jobTitle: member.jobTitle ?? "",
        industry: member.industry ?? "",
        civicInterests: text(member.civicInterests),
        skills: text(member.skills),
        availability: member.availability ?? "",
        city: member.city ?? "Fort Worth",
        state: member.state ?? "TX",
        zip: member.zip ?? "",
      }
    : undefined;
  return (
    <Suspense fallback={null}>
      <OnboardingForm
        initialReferralCode={referralCode}
        initialProfile={initialProfile}
        isProfileRepair={
          !!member?.termsAcceptedAt || member?.onboardingStatus === "completed"
        }
      />
    </Suspense>
  );
}
